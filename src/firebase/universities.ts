export function getDepartmentForMajor(major: string): string | null {
  return DEPARTMENT_BY_MAJOR[major] ?? null;
}

export function getUniversityName(email: string): string {
  const domain = email.split("@")[1]?.toLowerCase();
  if (!domain) return "";
  return UNIVERSITY_NAMES[domain] ?? domain.split(".")[0].toUpperCase();
}

export function getMajorsForUniversity(universityName: string): string[] {
  return MAJORS_BY_UNIVERSITY[universityName] ?? MAJORS_BY_UNIVERSITY["DEFAULT"];
}
